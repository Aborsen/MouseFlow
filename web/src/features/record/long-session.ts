/* A recording that outgrows one row.
 *
 * ЗДЕСЬ ЖИЛИ «СЕССИИ», и их больше нет - стоит записать, почему, потому что их сюда однажды уже привели те
 * же силы. Запись, которая не влезает одной строкой, была решена так: человек ДО старта выбирает «резать
 * каждые 30/60 минут», части едут на аккаунт с меткой session в payload, таблица записей их намеренно не
 * показывает, а показывает отдельная полоса Sessions, читающая леджер в localStorage. Три механизма и одна
 * предпосылка - что человек заранее знает, что запись выйдет длинной.
 *
 * Живой случай эту предпосылку опроверг: пять часов работы обычной записью, 154 975 событий, 9.1МБ - и
 * аккаунт отказал на остановке, когда выбирать было уже поздно. А когда починка нарезала запись в части,
 * они «доехали и пропали»: полоса читала леджер, куда никто не написал. Владелец продукта посмотрел на это
 * и сказал то, что стоило сказать раньше: не нужно отдельного блока - пусть запись режется САМА, когда
 * дошла до лимита, и каждая часть будет обычной записью в общем списке.
 *
 * Так и сделано. Причина резать одна - РАЗМЕР (часы были его прокси), отрезанное - обычная запись: события
 * на аккаунте, локальная строка с eventsOnAccount, тем же механизмом, которым записи и так выкладываются
 * при нехватке места. Ни метки session, ни леджера, ни полосы, ни выбора заранее.
 *
 * ЧИСЛА, НЕ МНЕНИЯ. Потолок строки на аккаунте - 8МБ развёрнутых событий (api/_payload.mjs). Событие весит
 * 52-69 байт - оба числа измерены на настоящих записях этого проекта, и разница между ними в полтора раза
 * значит, что оценка по константе врёт: где можно, вес МЕРЯЕТСЯ сериализацией.
 */
import type { AgentHealth } from '@/lib/agent';
import type { RecordedEvent, Recording } from '@/lib/store';
import { summarize } from '@/lib/macro';
import { flowFor } from './flow-for';

/* Целевой вес одной части, РАЗВЁРНУТЫЙ. Потолок аккаунта 8МБ; шесть оставляют место обёртке - имени, окнам,
 * флагам рекордера - и запас на то, что вес события в разных записях разный. */
export const FIT_TARGET_BYTES = 6_000_000;

/* Когда живая запись режется сама: по числу событий в буфере агента, потому что это единственное, что
 * статус-опрос сообщает. 75 000 × 69 байт (худший замеренный вес) ≈ 5.2МБ - внутри цели даже в худшем
 * случае. Прежнее число здесь было 4 500: оно считалось под потолок 400КБ и резало в двадцать раз чаще,
 * чем нужно. */
export const CUT_AT_EVENTS = 75_000;

/* ЗАПИСЬ, КОТОРАЯ НЕ ВЛЕЗЛА ОДНОЙ СТРОКОЙ, - в обычные записи.
 *
 * Один помощник на все три двери - остановку, «положить обратно» и импорт, - потому что причина отказа
 * одна (вес событий), и три своих нарезки разошлись бы первым же изменением.
 *
 * РАЗМЕР МЕРЯЕТСЯ, а не берётся из константы: события сериализуются один раз, и число событий в части
 * считается из ИХ веса. На пятичасовой записи событие весило ~52 байта против 69 «по константе» - оценка
 * соврала бы в полтора раза и нарезала бы втрое больше частей.
 *
 * ID ЧАСТЕЙ ДЕТЕРМИНИРОВАННЫЕ - `<id>-p1`, `-p2`, … api/sync.js делает upsert, поэтому повторная попытка
 * перезапишет те же строки, а не удвоит пять часов работы.
 *
 * ЧАСТИ ВОЗВРАЩАЮТСЯ С СОБЫТИЯМИ, и шелушит их ВЫЗЫВАЮЩИЙ - на успехе, `events: [], eventsOnAccount: true,
 * syncedAt`. Так у неудачной отправки остаётся, что повторять: каждая часть по построению меньше потолка,
 * Reconciler перепошлёт их поодиночке, и ни одна не отравит батч, как отравляла бы одна слишком большая
 * строка. `summary` посчитан здесь заранее - таблице есть что показать у строки, когда события уйдут. */
export function splitIntoRecordings(
  { rec, events, health, target = FIT_TARGET_BYTES }: {
    rec: Pick<Recording, 'id' | 'name' | 'created' | 'startedAt' | 'windows'>;
    events: RecordedEvent[];
    health: AgentHealth | null;
    target?: number;
  },
): { recs: Recording[]; flows: ReturnType<typeof flowFor>[]; bytes: number } {
  const bytes = JSON.stringify(events).length;
  const perPart = Math.max(500, Math.floor(events.length * (target / Math.max(bytes, 1))));

  const recs: Recording[] = [];
  const flows: ReturnType<typeof flowFor>[] = [];
  let n = 1;
  for (let i = 0; i < events.length; i += perPart) {
    const slice = events.slice(i, i + perPart);
    const part: Recording = {
      id: `${rec.id}-p${n}`,
      name: `${rec.name} · part ${n}`,
      created: rec.created,
      startedAt: rec.startedAt,
      events: slice,
      windows: rec.windows ?? [],
    };
    flows.push(flowFor(part, health));
    recs.push({ ...part, summary: summarize(slice) });
    n += 1;
  }
  return { recs, flows, bytes };
}
