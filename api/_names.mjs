/* Имя элемента без того, что приложение к нему приписало.
 *
 * ОТКУДА ЭТО. Дерево доступности отдаёт не заголовок вкладки, а предложение, которое браузер составил для
 * экранного диктора, - и в это предложение Chrome кладёт расход памяти:
 *
 *   Вкладка "Home - Google Drive" использует 448 МБ памяти
 *   Вкладка "(1) Chat / Margaryta Kashuba / Microsoft Teams" использует много памяти: 962 МБ
 *   webmachinelearning/webmcp: WebMCP - Memory usage - 299 MB
 *   Входящие - Viktor Horlenko - Outlook - High memory usage - 815 MB - Vic
 *
 * Двенадцать из ста восьмидесяти трёх записанных имён на живом аккаунте - то есть каждое пятнадцатое.
 *
 * ЭТО НЕ КОСМЕТИКА, хотя пришло как жалоба на внешний вид. Записанное имя - это то, по чему повтор
 * ЦЕЛИТСЯ: агент ищет в живом дереве элемент с таким же именем, потому что полоса вкладок перекладывается
 * и координате верить нельзя. Сравнение (sameName в агенте) требует, чтобы одно имя было префиксом другого.
 * А число мегабайт меняется каждую минуту - значит записанное «448 МБ» никогда не совпадёт с живым «512 МБ»,
 * и прицеливание по имени, написанное ровно ради вкладок, на вкладках же и отказывало. Молча: не найдя
 * имени, повтор возвращается к координате и кликает по тому, что оказалось на этом месте.
 *
 * ПОЧЕМУ ПРАВИЛО ЗДЕСЬ, А НЕ ТОЛЬКО В АГЕНТЕ. Агент чинит будущее: он может чистить имя при записи. Но сто
 * восемнадцать записей уже лежат с грязными именами, и их читают транскрипт, скилл и мастер. Эта функция
 * чинит прошлое - она стоит в ctxOf(), через который проходит КАЖДЫЙ разобранный контекст, - а агент чинит
 * прицел. Одно правило, два места, и test-contract.mjs держит их одинаковыми.
 *
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Списка локализованных слов Chrome. «Вкладка», «использует», «Memory usage» -
 * это три языка из сорока, и правило, собранное из строк, которые видели, врёт на первом же языке, которого
 * не видели. Поэтому распознаётся то, что от языка не зависит: ЧИСЛО С ЕДИНИЦЕЙ ПАМЯТИ. Оно и есть
 * единственная часть, которая меняется сама по себе, и единственная, ради которой всё это написано.
 */

/* Число с единицей объёма. Кириллические МБ/ГБ и латинские MB/GB - разные символы, поэтому перечислены
 * обе. Границы стоят, чтобы «15 GBP» и «MP3» не читались как объём. */
const SIZE = /(?<![\p{L}\p{N}.])\d+(?:[.,]\d+)?\s*(?:[КMМGГTТ]|Ki|Mi|Gi)?[BБ](?![\p{L}\p{N}])/u;

/* Слово «память» на том языке, на котором его написали. Не для распознавания - для того, чтобы отрезать
 * ВМЕСТЕ с ним: «- Memory usage - 299 MB» без этого превратилось бы в «- Memory usage». */
const MEMORY_WORD = /memoria|memory|mémoire|speicher|geheugen|pamię|paměť|memória|minne|muisti|bellek|памят|пам'ят|пам’ят|память/iu;

/** Разделители, на которых приложения вешают статусные приписки. */
const SPLIT = /\s+[-–—]\s+/;

const hasSize = (part) => SIZE.test(part);
const isMemoryClause = (part) => MEMORY_WORD.test(part) || hasSize(part);

/**
 * Имя, каким его прочитает человек и каким его найдёт повтор.
 *
 * Ничего не делает, когда делать нечего: имя без объёма памяти возвращается ровно тем, чем было. Это
 * важнее аккуратности - функция стоит на пути КАЖДОГО имени, и правило, срабатывающее «на всякий случай»,
 * молча переименовало бы кнопки, у которых всё было в порядке.
 *
 * @param {unknown} said
 * @returns {string} очищенное имя, или исходное, если чистить нечего
 */
export function plainName(said) {
  const name = typeof said === 'string' ? said.trim() : '';
  if (!name || !SIZE.test(name)) return name;

  /* ФОРМА ПЕРВАЯ: заголовок ЗАВЁРНУТ. «Вкладка "…" использует 448 МБ памяти» - настоящее имя в кавычках,
   * приписка с обеих сторон. Берётся содержимое кавычек, и только если после закрывающей кавычки ещё
   * что-то есть: имя, которое просто КОНЧАЕТСЯ кавычкой, - это имя, а не обёртка. */
  const wrapped = name.match(/^[^"«»]*[«"]([\s\S]+)[»"]\s*(\S[\s\S]*)$/);
  if (wrapped && wrapped[1].trim() && hasSize(wrapped[2])) return wrapped[1].trim();

  /* ФОРМА ВТОРАЯ: приписка ХВОСТОМ. «X - Memory usage - 299 MB», «X - High memory usage - 815 MB - Vic».
   * Отрезается от первого куска, который относится к памяти, и до конца: то, что стоит ЗА статусом, -
   * тоже статус (имя профиля, номер окна), и никакой из этих кусков не является частью имени. */
  const parts = name.split(SPLIT);
  if (parts.length > 1) {
    const cut = parts.findIndex((part, i) => i > 0 && isMemoryClause(part));
    /* Отрезать можно только если что-то остаётся. Имя, которое ЦЕЛИКОМ про память, - это имя, и лучше
     * показать его как есть, чем пустую строку. */
    if (cut > 0) {
      const kept = parts.slice(0, cut).join(' - ').trim();
      if (kept) return kept;
    }
  }

  /* ФОРМЫ ТРЕТЬЕЙ НЕТ, и это решение, а не пропуск.
   *
   * Напрашивалась такая: если ни кавычек, ни разделителя нет, отрезать по самому числу - «… использует
   * 448 МБ памяти» без кавычек. Написана она была, и на двенадцати настоящих именах не сработала ни разу:
   * все двенадцать ловятся первыми двумя. Зато на проверке она превратила «Upgrade to 200 GB storage» в
   * «Upgrade to», «Free up 2 GB now» в «Free up», а «Storage: 15 GB used» в «Storage».
   *
   * Это не косметическая ошибка. Переименованная кнопка - это кнопка, которую повтор больше не найдёт в
   * живом дереве, и вместо неё кликнет по координате. То есть правило, написанное чинить прицел, ломало бы
   * прицел там, где он работал, - ради случая, которого в данных нет. Убрано.
   */

  return name;
}
