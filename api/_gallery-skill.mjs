/* Что именно уезжает в галерею, и почему у приложения это до сих пор не получалось.
 *
 * СИМПТОМ. Кнопка Publish на странице Skills отвечала «unrecognised skill format» на КАЖДЫЙ скилл, который
 * это приложение способно сделать. Не на какой-то один - на все.
 *
 * ПРИЧИНА. api/gallery.js требует `format: 'mouseflow.skill/1'` и делает это правильно: маршрут публичный,
 * туда может постучаться что угодно, и правила, на которые галерея опирается, обязаны проверяться там, где
 * галерея. Строку эту ставит extension/skills.js, потому что формат придумали для расширения. Приложение же
 * посылало в галерею СВОЙ payload - тот, что лежит на аккаунте у flow, - а он другой формы: version, kind,
 * agent, role, events... и никакого format. То есть две половины продукта говорили о скилле на разных
 * языках, и общего у них была только кнопка.
 *
 * ЧТО ЗДЕСЬ. Перевод одной формы в другую, в одном месте, рядом с маршрутом - тем же приёмом, что
 * _flow-for.mjs и _skill-schema.mjs: функция живёт в api/, web-приложение читает её шимом, и разойтись
 * копиям негде, потому что копии нет.
 *
 * ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ - и это половина смысла файла. Из payload'а вычищается всё, что верно только на
 * машине автора:
 *
 *   publishedAs / publishedAt   id ЭТОЙ публикации. Уехав в галерею, он приезжает установившему - и его
 *                               приложение начинает считать свою частную копию опубликованной, показывать
 *                               «Published» и предлагать снять с публикации чужой скилл. Отобрать он его не
 *                               сможет (проверка автора у галереи в WHERE), но экран будет врать.
 *   fromRecording / fromRun     ссылка на запись или прогон на аккаунте автора. У установившего таких строк
 *                               нет, и «показать запись, из которой это сделано» ведёт в пустоту.
 *
 * А name, description и origins берутся из СТРОКИ flow, а не из payload'а: переименование правит строку, и
 * payload у записи имени может не нести вовсе.
 */

/* ВЕРСИЯ ФОРМАТА ОБМЕНА - и почему её здесь ДВЕ.
 *
 * Пишется всегда последняя; читаются обе. `/1` уже уехал с чьей-то машины в файле, и отказаться его
 * читать значит сломать то, что человек считает своим, - поэтому старый формат остаётся принимаемым
 * навсегда. Разница между «что мы пишем» и «что мы принимаем» - это и есть формат обмена; одна константа
 * на оба вопроса отвечала бы неверно на второй.
 *
 * Те же две строки стоят в extension/skills.js - вторая половина продукта, другой рантайм, импортировать
 * оттуда сюда нечем. Их согласие закреплено в api/_test-gallery.mjs, и это закрепление тут единственное,
 * что не даёт половинам разъехаться. */
export const SKILL_FORMAT = 'mouseflow.skill/2';
export const SKILL_FORMATS_READ = ['mouseflow.skill/2', 'mouseflow.skill/1'];

/** Что не должно уезжать с чужой машины. */
const LOCAL_ONLY = ['publishedAs', 'publishedAt', 'fromRecording', 'fromRun'];

/**
 * Скилл в том виде, в каком его принимает POST /api/gallery.
 *
 * @param {{name?: string, description?: string, origins?: string[]}} flow  строка на аккаунте
 * @param {Record<string, unknown>} payload                                 её payload
 */
export function skillForGallery(flow, payload) {
  const out = {};
  for (const [key, value] of Object.entries(payload || {})) {
    if (!LOCAL_ONLY.includes(key)) out[key] = value;
  }
  /* ФОРМАТ, КОТОРЫЙ У НЕГО УЖЕ ЕСТЬ, если он нам знаком, - и только иначе наш.
   *
   * Стояло безусловное присваивание, и после появления `/2` оно стало ложью: `/1`-скилл, у которого нет
   * и не может быть процедуры, уезжал бы в галерею с меткой `/2` - то есть обещал бы читателю уровень,
   * которого в нём нет. Свою версию ставим тому, кто не назвал никакой (так приложение и присылало свои,
   * из-за чего отказ прилетал на каждый), а названную знакомую оставляем как есть. */
  out.format = SKILL_FORMATS_READ.includes(out.format) ? out.format : SKILL_FORMAT;
  out.name = String((flow && flow.name) || out.name || 'Untitled skill');
  out.description = String((flow && flow.description) || out.description || '');
  /* Галерея читает origins ИЗ PAYLOAD'А, а приложение держит их на строке. Без этого каждая карточка в
   * галерее была бы «нигде»: список показывает, где скилл работает, и брать это ему неоткуда. */
  out.origins = Array.isArray(flow && flow.origins) ? flow.origins.slice(0, 12) : [];
  /* Пустой список параметров - это ответ, а не пропуск: у записанного скилла их и не бывает, а галерея
   * вычищает по нему примеры из имени и описания и на отсутствующем поле вычистила бы ничто. */
  if (!Array.isArray(out.params)) out.params = [];
  return out;
}
