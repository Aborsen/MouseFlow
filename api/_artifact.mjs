/* Какие кадры прогона стоит сохранить, а какие выбросить.
 *
 * ЗАЧЕМ ЭТО ЧИСТЫЙ МОДУЛЬ. Решение «какие двенадцать из двадцати оставить» принимается в двух местах -
 * облачный путь пишет строки сам, браузерный присылает их маршрутом, - и разойдясь, они дали бы отчёты,
 * в которых у одного прогона есть картинка провала, а у такого же другого нет. Плюс это единственная часть
 * артефактов, которую можно проверить вычислением, и она же единственная, где легко потерять именно то, что
 * нужно: провал.
 *
 * ГЛАВНОЕ ПРАВИЛО: ПРОВАЛ НЕ ВЫБРАСЫВАЕТСЯ. Когда кадров больше потолка, уходят самые старые ПРОШЕДШИЕ
 * проверки - они подтверждают то, что и так зелёное. Кадр провала и последний кадр прогона остаются всегда:
 * ради них таблица и существует.
 */

/* Вес одного кадра. Агент присылает JPEG в ширине, которую просил цикл (обычно 1280), и это ~100-200КБ;
 * четверть мегабайта - потолок с запасом, а не цель. Кадр тяжелее не уменьшается тихо: он ОТКЛАДЫВАЕТСЯ с
 * причиной, потому что уменьшить его здесь нечем - в этом модуле нет ни канваса, ни картинок. */
export const ARTIFACT_MAX_BYTES = 250_000;

/* Сколько кадров на один прогон. Двенадцать - это провал, финал и десять проверок; прогон, сделавший
 * сорок проверок, - это не отчёт, который кто-то будет разглядывать целиком. */
export const ARTIFACTS_PER_RUN = 12;

/* Сколько они живут. Тридцать суток - потому что смысл картинки в диагностике, а диагностируют по горячему:
 * провал, к которому не вернулись за месяц, не вернутся уже никогда, а место он занимает всё это время.
 * Убирается лениво, на записи следующего, - тем же приёмом, что и расписания, и по той же причине: крон в
 * облаке это второй механизм, который может сломаться незаметно. */
export const ARTIFACT_KEEP_DAYS = 30;

/** Виды, от самого нужного к самому необязательному. Порядок ЗНАЧИМ - по нему решается, что выбросить. */
export const KINDS = ['failure', 'final', 'check'];

export const artifactId = () =>
  `art_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;

/** Слишком тяжёлый кадр не пишется, и это говорится словами, а не тишиной. */
export function tooBig(bytes) {
  const n = typeof bytes === 'string' ? bytes.length : Number(bytes) || 0;
  return n > ARTIFACT_MAX_BYTES
    ? `${Math.round(n / 1024)}KB is over the ${Math.round(ARTIFACT_MAX_BYTES / 1024)}KB a kept frame may `
      + 'weigh, so it was not kept. The run and its words are unaffected.'
    : null;
}

/**
 * ЧТО ВЫБРОСИТЬ, когда кадров стало больше потолка.
 *
 * @param {{id: string, kind: string, step_no: number}[]} have  уже лежащие у этого прогона, любым порядком
 * @param {number} adding  сколько добавляется сейчас
 * @returns {string[]} id тех, что надо удалить - самые старые ПРОШЕДШИЕ проверки первыми
 */
export function dropWhich(have, adding = 0) {
  const rows = Array.isArray(have) ? have.slice() : [];
  const over = rows.length + Math.max(0, adding) - ARTIFACTS_PER_RUN;
  if (over <= 0) return [];
  /* Порядок выбрасывания: сначала проверки, и внутри них - самые ранние шаги. Провалы и финал в конце
   * списка, то есть уходят последними и только если вообще ничего другого не осталось. */
  const rank = (row) => {
    const k = KINDS.indexOf(String(row && row.kind));
    return k === -1 ? KINDS.length : k;
  };
  rows.sort((a, b) => (rank(b) - rank(a)) || (Number(a.step_no) - Number(b.step_no)));
  return rows.slice(0, over).map((row) => String(row.id));
}

