/* ТО, ЧТО ЧЕЛОВЕК ВЫБРАЛ, А ЗАПИСЬ НЕ УВИДЕЛА - и то, что записал сам рекордер о себе.
 *
 * Здесь ровно два вопроса, и оба про шаги, которым в скилле делать нечего в том виде, в каком они пришли.
 *
 * ПЕРВЫЙ - наши собственные кнопки. Каждая запись заканчивается нажатием на «стоп», и скилл, который его
 * честно повторяет, жмёт стоп у рекордера, которого никто не запускал.
 *
 * ВТОРОЙ - клик, попавший В САМУ СТРАНИЦУ. Замер на живой записи: после кнопки « Add filter» идут три
 * клика с type=document и именем «Order search» - это имя ДОКУМЕНТА, а не того, во что попали. Как шаги
 * они превращались в «click "Order search"» трижды подряд: строчка, по которой ничего сделать нельзя, и
 * при этом единственное место, где человек выбрал, ЧТО именно фильтровать. Запись этого не знает и знать не
 * может - выбор жил в разметке, у которой accessibility-имени не оказалось.
 *
 * Поэтому такой клик не выбрасывается, а становится МЕСТОМ ДЛЯ ОТВЕТА: «click " Add filter"» плюс то, что
 * человек допишет своими словами. Это то же решение, что и у набора текста, - запись не подглядывает, а
 * спрашивает один раз, когда скилл делают.
 *
 * Живёт рядом с API, а не в .tsx: так это гоняет узловой набор тестов против настоящих записей. Классификатор,
 * проверенный регуляркой по .tsx, - это классификатор, который никто не запускал.
 */

/* НАШИ СОБСТВЕННЫЕ органы управления записью.
 *
 * Совпадение ПО ИМЕНИ, что безопасно ЗДЕСЬ и больше нигде: это наши подписи в нашем продукте, взятые из
 * нашего же исходника, и, в отличие от типа контрола, они не переводятся. Строки - те, что действительно
 * стоят в веб-приложении и в агенте. */
export const OWN_RECORDER_CONTROLS = [
  'stop and save this recording',
  'stop and save recording',
  'start recording',
];

/* ИМЯ АГЕНТА, и матчится ВХОЖДЕНИЕМ, а не равенством. Причина измерена: у агента в трее подсказка -
 * «MouseFlow agent - recording», а панель задач Windows отдаёт accessibility-имя кнопки как имя приложения
 * ПЛЮС заголовок, то есть «MouseFlow agent MouseFlow agent - recording». Равенство такое не поймает никогда,
 * и именно этот шаг доезжал до скилла последним пунктом («нажать стоп»).
 *
 * Вхождение здесь не грубее равенства, а точнее: любое окно нашего агента для запуска недосягаемо в
 * принципе - агент отказывается управлять своими же окнами («that window belongs to the MouseFlow agent
 * itself», agent/mouseflow-agent.ps1). Шаг, который нельзя выполнить по устройству, в скилле не нужен. */
export const OWN_AGENT_MARK = 'mouseflow agent';

export function isOwnRecorderControl(line) {
  const name = String((line && line.control) || '').trim().toLowerCase();
  if (!name) return false;
  if (name.includes(OWN_AGENT_MARK)) return true;
  return OWN_RECORDER_CONTROLS.includes(name);
}

/* ТИПЫ-КОНТЕЙНЕРЫ: попасть в них значит попасть в страницу, а не в элемент.
 *
 * Список английский, а `type` приходит от UIA как LocalizedControlType, то есть на локализованной Windows
 * будет на её языке. Это осознанно и ровно так же уже сделано в самом агенте (LandmarkTypes сравнивается с
 * английскими строками): промах здесь стоит НЕ предложенной подсказки, а не неверного шага. Отказ в пользу
 * тишины, а не в пользу выдумки. */
export const CONTAINER_TYPES = [
  'document', 'main', 'pane', 'group', 'client', 'window', 'web area', 'section', 'form',
  'list', 'table', 'tree', 'data grid', 'grid',
];

const CLICKS = ['click', 'dblclick'];

export function isContainerClick(line) {
  if (!line || !CLICKS.includes(line.action)) return false;
  /* Без имени это и так неописуемый шаг - он уже сложен в отсев, и отдельного разговора не заслуживает. */
  if (!line.control) return false;
  const type = String(line.controlType || '').trim().toLowerCase();
  return !!type && CONTAINER_TYPES.includes(type);
}

/* Шаг, который может ОТКРЫТЬ выбор: названный клик не по контейнеру. Ни набор текста, ни клавиша - у них
 * свой разговор, и они же разрывают серию ниже. */
const opensChoice = (line) => !!line && CLICKS.includes(line.action)
  && !!line.control && !isContainerClick(line) && !isOwnRecorderControl(line);

/* Что серию НЕ разрывает: движения, паузы и прокрутка. Они не действия - см. instruction() в визарде. */
const PASSES = ['move', 'wait', 'scroll'];

/**
 * СЕРИИ КЛИКОВ ПО СТРАНИЦЕ, каждая - одно место для ответа.
 *
 * Серия, а не шаг: замер даёт 15, 23 и 25 подряд (между ними только прокрутка и пауза), и это ОДИН выбор -
 * «какой фильтр», - а не три. Три одинаковых карточки «clicked the "Order search" document» человек не
 * различит, и это ровно та беда, от которой в наборе текста существует нумерация nth/of.
 *
 * ТОЛЬКО ТАМ, ГДЕ ВЫБОР КТО-ТО ОТКРЫЛ, и это ограничение измерено, а не осторожность ради осторожности.
 * Клик по телу страницы - штука рядовая: на записи из 6705 шагов таких серий 144, и почти все они - клик по
 * пустому месту, снятие фокуса, закрытие подсказки. Спрашивать «что вы здесь выбрали» у каждой значит
 * задать сто сорок четыре вопроса ни о чём - тот самый провал, от которого в этом файле рядом стоит отбор
 * набора текста. С требованием открывающего клика остаётся 29, а на записи, с которой пришла жалоба, - 2, и
 * обе те самые: « Add filter» и «L1».
 *
 * ЯКОРЬ - НАЗВАННЫЙ КЛИК ПЕРЕД СЕРИЕЙ: спросили-то про шаг «Click " Add filter"», и ответ должен стоять
 * там, где человек его ищет. Шаг скилла тогда читается «click " Add filter", then ...» - два предложения об
 * одном действии, а не сирота после него. Серия без открывающего клика остаётся ровно тем, чем была до
 * этого файла: обычными шагами, которые видно и можно снять галочкой.
 */
export function choiceRuns(lines) {
  const list = Array.isArray(lines) ? lines : [];
  const runs = [];
  let run = null;
  /* Последний названный клик - кандидат в якоря, и живёт он только до следующего настоящего действия. */
  let opener = null;
  let place = null;

  for (const line of list) {
    if (!line || typeof line.n !== 'number') continue;
    /* Смена места разрывает всё: другой сайт - другой выбор. `url` точнее заголовка, но есть не везде. */
    const here = line.url || line.host || line.where || null;
    if (here !== place) {
      place = here;
      run = null;
      opener = null;
    }
    if (PASSES.includes(line.action)) continue;

    if (isContainerClick(line)) {
      if (run) {
        run.steps.push(line.n);
        run.clicks += 1;
        continue;
      }
      if (opener) {
        run = {
          n: opener.n,
          after: opener.control,
          steps: [line.n],
          clicks: 1,
          where: line.host || line.where || null,
        };
        runs.push(run);
      }
      /* Без открывающего клика - не серия, а обычный шаг. Молча: см. заметку выше. */
      continue;
    }

    run = null;
    opener = opensChoice(line) ? line : null;
  }

  /* Что показать и что спрятать - двумя готовыми справочниками, чтобы вызывающему не пересчитывать одно и
   * то же на каждой строке списка из 546 штук. */
  const anchors = new Map();
  const hushed = new Set();
  for (const one of runs) {
    anchors.set(one.n, one);
    /* Сами клики по странице прячутся ВСЕ: вопрос стоит на открывающем шаге и отвечает за них. Как шаги они
     * давали «click "Order search"» трижды - строчку, по которой ничего сделать нельзя. */
    for (const n of one.steps) hushed.add(n);
  }
  return { runs, anchors, hushed };
}
