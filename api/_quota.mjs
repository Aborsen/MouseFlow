/* Чем поступиться, когда консоль не помещается на диск - и чем не поступиться никогда.
 *
 * ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ ФАЙЛ И ПОЧЕМУ ОН ЗДЕСЬ. Правило состоит из одного запрета, и запрет этот -
 * единственное, что стоит между «мы освободили место» и «мы стёрли единственную копию чьей-то работы».
 * Регулярка над исходником сказала бы, что функция похожа на правильную; выполнить её можно только если она
 * чистая и лежит там, откуда её достанет node. Рядом с API - потому что здесь уже живут `_flow-for.mjs` и
 * `_macro.mjs`, которые читают и приложение, и сервер, и по той же причине: одно правило в одном месте.
 *
 * ЧТО ЗДЕСЬ ПРОИСХОДИТ. localStorage даёт около 5000КБ на весь origin, а консоль пишется ОДНОЙ строкой -
 * все записи вместе. Четырёхчасовая запись это 5850КБ сама по себе, то есть не помещается вовсе; и
 * поскольку строка одна, одна такая запись роняла запись ВСЕГО остального: штампа `syncedAt`, квитанции о
 * синхронизации, любой другой записи, сделанной в той же сессии. Молча.
 *
 * ОТСТУПЛЕНИЕ. Самые большие записи, УЖЕ ЛЕЖАЩИЕ НА АККАУНТЕ, отдают свои события - по одной, начиная с
 * самой большой, пока не поместится. Строка остаётся: имя, счётчики, окна, штамп. События возвращаются с
 * аккаунта по требованию.
 *
 * ЗАПРЕТ. Запись БЕЗ штампа не отдаёт события никогда. У неё нет второй копии, и выложить её события значит
 * их потерять - то есть сделать ровно то, ради предотвращения чего всё это написано. Если поместиться можно
 * только за её счёт, не помещаемся и говорим об этом.
 *
 * И НЕ «выбросить самые старые», хотя это короче и всегда помещается: человек не давал согласия терять
 * записи, а тот, кто молча удаляет данные, чтобы влезть в квоту, второй раз доверия не получит.
 */

/** Есть ли у записи вторая копия - то есть можно ли отпускать её события. */
export const heldElsewhere = (rec) => !!(rec && rec.syncedAt);

/**
 * В каком порядке записи отдают свои события. Самая большая первой; кандидатом считается только та, у
 * которой есть вторая копия на аккаунте и есть что отдавать.
 *
 * @param {Array<{id: string, syncedAt?: string, events?: unknown[], borrowed?: boolean}>} recordings
 * @returns {string[]} id, от самой большой к меньшей
 */
export function freeingOrder(recordings) {
  const list = Array.isArray(recordings) ? recordings : [];
  return list
    .filter((rec) => rec && rec.id && heldElsewhere(rec))
    .filter((rec) => Array.isArray(rec.events) && rec.events.length > 0)
    .map((rec) => ({ id: rec.id, size: rec.events.length }))
    /* По убыванию, а при равенстве - по id, чтобы порядок был один и тот же на двух одинаковых входах:
     * тест, который иногда проходит, хуже отсутствующего. */
    .sort((a, b) => (b.size - a.size) || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
    .map((one) => one.id);
}
